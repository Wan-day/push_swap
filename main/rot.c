#include "libft.h"

void	ra(t_stack **a)
{
	if ((*a) == NULL || (*a)->next == (*a))
		return ;
	(*a) = (*a)->next;
}

void	rb(t_stack **b)
{
	if ((*b) == NULL || (*b)->next == (*b))
		return ;
	(*b) = (*b)->next;
}

void	rr(t_stack **a, t_stack **b)
{
	ra(a);
	rb(b);
}
